def normalize_locale(value: str | None) -> str:
    if value in SUPPORTED_LOCALES:
        return value
    return DEFAULT_LOCALE


def get_locale_from_info(info: dict[str, str] | None) -> str:
    if not info:
        return DEFAULT_LOCALE
    return normalize_locale(info.get("locale"))


def get_locale_from_db(db: Session) -> str:
    row = db.query(Info).filter(Info.field == "locale").first()
    return normalize_locale(row.value if row else None)


def translate(locale: str, text: str, **kwargs) -> str:
    locale = normalize_locale(locale)
    result = text if locale == "ru" else EN_TEXTS.get(text, text)
    return result.format(**kwargs) if kwargs else result


def status_label(status: str, locale: str) -> str:
    mapping = {
        "actively": "Активно ищу работу",
        "passively": "Открыт к предложениям",
        "none": "Сейчас не в поиске",
    }
    return translate(locale, mapping.get(status, mapping["none"]))


def locale_label(locale_code: str, locale: str) -> str:
    labels = {
        "ru": "Русский",
        "en": "Английский",
    }
    return translate(locale, labels.get(locale_code, locale_code))
